'use strict';

// Cloudinary-backed storage for CBTKU exam question images.
// Neon stores only a compact reference: cloudinary://cbtku-questions/<uuid>.
// Image payloads are strictly size-limited before they reach Cloudinary.
require('dotenv').config();

const { randomUUID } = require('crypto');
const cloudinary = require('cloudinary').v2;

const MAX_QUESTION_IMAGE_BYTES = 500 * 1024; // server-side hard limit; UI target is <= 450 KB
const ALLOWED_CONTENT_TYPES = Object.freeze({
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp'
});

function isConfigured() {
  return Boolean(
    process.env.CLOUDINARY_CLOUD_NAME &&
    process.env.CLOUDINARY_API_KEY &&
    process.env.CLOUDINARY_API_SECRET
  );
}

function configureCloudinary() {
  if (!isConfigured()) {
    throw new Error('Penyimpanan gambar belum dikonfigurasi. Atur CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY, dan CLOUDINARY_API_SECRET pada environment server.');
  }
  cloudinary.config({
    cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
    api_key: process.env.CLOUDINARY_API_KEY,
    api_secret: process.env.CLOUDINARY_API_SECRET,
    secure: true
  });
  return cloudinary;
}

function isCloudinaryImageRef(imageRef) {
  return typeof imageRef === 'string' && imageRef.startsWith('cloudinary://');
}

function cloudinaryPublicIdFromRef(imageRef) {
  if (!isCloudinaryImageRef(imageRef)) return null;
  const publicId = imageRef.slice('cloudinary://'.length);
  // All IDs are generated by this service; do not allow arbitrary public IDs.
  if (!/^cbtku-questions\/[0-9a-f-]{36}$/i.test(publicId)) {
    throw new Error('Referensi gambar Cloudinary tidak valid.');
  }
  return publicId;
}

function checkImageSignature(buffer, contentType) {
  if (!Buffer.isBuffer(buffer) || buffer.length === 0) {
    throw new Error('Berkas gambar kosong atau tidak valid.');
  }
  if (buffer.length > MAX_QUESTION_IMAGE_BYTES) {
    throw new Error('Ukuran gambar setelah kompresi maksimal 500 KB. Pilih gambar lain atau kompres kembali.');
  }

  let matches = false;
  if (contentType === 'image/jpeg') {
    matches = buffer.length >= 3 && buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff;
  } else if (contentType === 'image/png') {
    matches = buffer.length >= 8 && buffer.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]));
  } else if (contentType === 'image/webp') {
    matches = buffer.length >= 12 && buffer.toString('ascii', 0, 4) === 'RIFF' && buffer.toString('ascii', 8, 12) === 'WEBP';
  }

  if (!matches) {
    throw new Error('Isi berkas tidak cocok dengan format gambar yang diizinkan. Gunakan JPG, PNG, atau WebP.');
  }
}

async function uploadQuestionImage(buffer, contentType) {
  if (!ALLOWED_CONTENT_TYPES[contentType]) {
    throw new Error('Format gambar tidak didukung. Gunakan JPG, PNG, atau WebP.');
  }
  checkImageSignature(buffer, contentType);
  const client = configureCloudinary();
  const publicId = `cbtku-questions/${randomUUID()}`;

  const result = await new Promise((resolve, reject) => {
    const stream = client.uploader.upload_stream({
      resource_type: 'image',
      type: 'authenticated',
      public_id: publicId,
      overwrite: false,
      unique_filename: false,
      use_filename: false,
      tags: ['cbtku-question-images']
    }, (error, uploaded) => {
      if (error) return reject(error);
      if (!uploaded || !uploaded.public_id) return reject(new Error('Cloudinary tidak mengembalikan identitas gambar.'));
      resolve(uploaded);
    });
    stream.end(buffer);
  });

  return {
    public_id: result.public_id,
    bytes: result.bytes,
    format: result.format
  };
}

function resolveImageDisplayUrl(imageRef) {
  if (!imageRef) return null;
  if (!isCloudinaryImageRef(imageRef)) {
    // Keep existing ordinary HTTPS image links and legacy Data URLs readable.
    if (String(imageRef).startsWith('r2://')) {
      throw new Error('Referensi gambar Cloudflare R2 lama tidak dapat digunakan pada konfigurasi Cloudinary. Silakan unggah ulang gambar soal.');
    }
    return imageRef;
  }

  const client = configureCloudinary();
  const publicId = cloudinaryPublicIdFromRef(imageRef);
  // Authenticated assets require the signature in the delivery URL.
  // Cloudinary validates the signature before returning the asset.
  return client.url(publicId, {
    resource_type: 'image',
    type: 'authenticated',
    secure: true,
    sign_url: true
  });
}

async function deleteStoredImage(imageRef) {
  if (!isCloudinaryImageRef(imageRef)) return;
  const client = configureCloudinary();
  const publicId = cloudinaryPublicIdFromRef(imageRef);
  await client.uploader.destroy(publicId, {
    resource_type: 'image',
    type: 'authenticated',
    invalidate: true
  });
}

module.exports = {
  isConfigured,
  isCloudinaryImageRef,
  cloudinaryPublicIdFromRef,
  uploadQuestionImage,
  resolveImageDisplayUrl,
  deleteStoredImage,
  ALLOWED_CONTENT_TYPES,
  MAX_QUESTION_IMAGE_BYTES
};
